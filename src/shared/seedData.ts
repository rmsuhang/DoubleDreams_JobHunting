export function createInitialSeedState(): AppDataState {
  const now = new Date();
  const shanghaiMs = now.getTime() + 8 * 60 * 60 * 1000;
  const d = new Date(shanghaiMs);
  const todayStr = `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, '0')}-${String(
    d.getUTCDate()
  ).padStart(2, '0')}`;

  const emptyBaseline: BriefingSnapshot = {
    id: `brief-baseline-${todayStr}`,
    briefingDate: todayStr,
    generatedAt: now.toISOString(),
    triggerType: 'baseline',
    baselineBriefingId: null,
    baselineDate: null,
    sourcesCheckedCount: INITIAL_OFFICIAL_SOURCES.length,
    liveScanUsed: false,
    scanStatusMessage:
      '已切换为纯真实官源模式（已清空示例假数据）。请点击“立即汇总今日公告”或运行每日 08:00 自动检索，仅展示真实抓取并核验的官方公告原文。',
    stats: {
      totalMatched: 0,
      newCount: 0,
      updatedCount: 0,
      stillOpenCount: 0,
      anomalyCount: 0,
      tcmPhysicianCount: 0,
      medicalCraCount: 0,
    },
    items: [],
    groundingLinks: [],
  };

  return {
    profile: INITIAL_PROFILE,
    sources: INITIAL_OFFICIAL_SOURCES,
    schedule: {
      enabled: true,
      triggerTime: '08:00',
      timezone: 'Asia/Shanghai',
      lastRunAt: null,
      nextRunAt: computeNextTriggerIso('08:00', now),
    },
    briefings: [emptyBaseline],
  };
}
